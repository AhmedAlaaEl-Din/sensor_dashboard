// Configuration for the local API.
//
// Secrets: the JWT signing key is generated on first start and written to
// api/.env (git-ignored). Its value is never logged or printed.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const API_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const REPO_ROOT = path.resolve(API_DIR, '..');

const LOOPBACK = new Set(['127.0.0.1', '::1', 'localhost']);

/** Minimal KEY=VALUE parser (no quotes or expansion needed here). */
export function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

/**
 * Makes sure api/.env exists and holds a JWT secret. Returns the parsed file.
 * Only the key name is ever logged, never the value.
 */
export function ensureEnvFile(envPath = path.join(API_DIR, '.env'), log = () => {}) {
  let vars = {};
  if (fs.existsSync(envPath)) vars = parseEnv(fs.readFileSync(envPath, 'utf8'));
  if (!vars.JWT_SECRET || vars.JWT_SECRET.length < 32) {
    vars.JWT_SECRET = crypto.randomBytes(48).toString('base64url');
    const body =
      '# Generated by the sensor-dashboard API on first start. Local secrets: never commit.\n' +
      Object.entries(vars)
        .map(([k, v]) => `${k}=${v}`)
        .join('\n') +
      '\n';
    fs.writeFileSync(envPath, body, { mode: 0o600 });
    log(`generated a new JWT_SECRET in ${path.relative(REPO_ROOT, envPath)}`);
  }
  return vars;
}

function num(value, fallback) {
  const n = Number(value);
  return Number.isFinite(n) && n > 0 ? n : fallback;
}

/** Builds the runtime config. Environment variables override api/.env. */
export function loadConfig({ env = process.env, log = () => {} } = {}) {
  const fileVars = ensureEnvFile(undefined, log);
  const get = (k) => env[k] ?? fileVars[k];

  const host = get('API_HOST') ?? '127.0.0.1';
  if (!LOOPBACK.has(host)) {
    throw new Error(`Refusing to listen on "${host}": the API is local-only (use 127.0.0.1).`);
  }

  return {
    host,
    port: num(get('API_PORT'), 3000),
    jwtSecret: get('JWT_SECRET'),
    tokenTtlSeconds: num(get('TOKEN_TTL_SECONDS'), 30 * 60),
    dbPath: get('DB_PATH') ?? path.join(REPO_ROOT, 'data', 'history.db'),
    mqttUrl: get('MQTT_URL') ?? 'mqtt://127.0.0.1:1883',
    topicPrefix: get('TOPIC_PREFIX') ?? 'sensors',
    retentionDays: num(get('RETENTION_DAYS'), 7),
    cleanupIntervalMs: num(get('CLEANUP_INTERVAL_MS'), 60 * 60 * 1000),
    demoAdminPassword: get('DEMO_ADMIN_PASSWORD') ?? DEMO_PASSWORDS.admin,
    demoViewerPassword: get('DEMO_VIEWER_PASSWORD') ?? DEMO_PASSWORDS.viewer,
  };
}

/**
 * Demo-only accounts for the local demo. These are documented in the README on
 * purpose: they protect nothing real and exist only on 127.0.0.1.
 */
export const DEMO_USERS = {
  admin: 'admin@example.com',
  viewer: 'viewer@example.com',
};
export const DEMO_PASSWORDS = {
  admin: 'admin-demo-pass',
  viewer: 'viewer-demo-pass',
};
